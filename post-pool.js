// app・媒体に合う材料のうち、まだ使っていない本文を返す。同じ日に同じ話題（topic）を重ねない。
// taken：すでにある本文の集合（`${sns}\0${本文}`）。usedTopicsToday：その日に選んだ話題。start：材料を回す開始位置。
function pickFromPool({ app, sns, taken, usedTopicsToday, start = 0 }) {
  const items = POOL.filter((p) => p.app === app && p.sns === sns);
  for (let i = 0; i < items.length; i++) {
    const item = items[(start + i) % items.length];
    if (taken.has(`${sns}\0${item.text}`) || usedTopicsToday.has(item.topic)) continue;
    return item;
  }
  return null;
}

module.exports = { POOL, pickFromPool };
